export function seedCards() {
  // 幂等补种：按 (domain, front) 去重——已存在的卡跳过，缺失的补齐（支持内容升级）
  const exists = new Set(db.prepare('SELECT domain, front FROM knowledge_cards').all().map((r) => `${r.domain}|${r.front}`));
  const today = new Date().toISOString().slice(0, 10);
  const ins = db.prepare(`INSERT INTO knowledge_cards (domain, front, back, sources, level_tag, next_review) VALUES (?,?,?,?,?,?)`);
  let added = 0;
  for (const [d, f, b, s, tag] of SEEDS) {
    const key = `${d}|${f}`;
    if (exists.has(key)) continue;
    ins.run(d, f, b, s, tag, today);
    added += 1;
  }
  const total = db.prepare('SELECT COUNT(*) c FROM knowledge_cards').get().c;
  return { seeded: added > 0, added, total };
}
